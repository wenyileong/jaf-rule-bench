"""Empirical design: episodes, observations, measurement attributes, estimation settings and hypotheses
(build plan s 14, components B1 and B7).

A design says which observed facts the model is to be confronted with, under which version of the coded law
(an episode), and how each fact was measured. It never contains model outputs. Values may be blank: a design
with blank values is what is frozen for pre-registration before any data are examined.
"""
from __future__ import annotations
import copy, hashlib, json
from dataclasses import dataclass, field, asdict, fields
from .world import World, Jurisdiction, Settings

BASELINE = "baseline"
ROLES = ("target", "holdout")
COMPARISONS = ("ratio", "difference")

# Fields an episode may change. Jurisdiction fields by name; settings fields under the pseudo-code "settings".
EPISODE_J_FIELDS = ("liability_rule", "intermediary_test", "collection", "domestic_exchanges_permitted",
                    "visibility_domestic_custodial", "visibility_self_hosted", "info_exchange_from", "residence_topup",
                    "rate_mode", "effective_rate", "exchange_presence", "holder_base",
                    "offshore_incorporation_in", "offshore_incorporation_share")
EPISODE_S_FIELDS = ("scenario_year", "visibility_exchanged", "treaty_relief")


@dataclass
class Change:
    target: str              # jurisdiction code, or "settings"
    field: str
    value: object
    source: str = ""
    verified: bool = False


@dataclass
class Episode:
    name: str
    description: str = ""
    changes: list = field(default_factory=list)   # list[Change], applied to the coded world in order


@dataclass
class Observation:
    id: str
    quantity: str
    code: str = ""                 # jurisdiction the quantity refers to ("" for world-level quantities)
    episode: str = BASELINE
    compared_with: str = ""       # another episode: the observation is then a ratio or difference between the two
    comparison: str = "ratio"
    value: float | None = None     # blank before data are loaded (pre-registration)
    sd: float | None = None        # measurement standard error, in the units of the value
    role: str = "target"           # target: used to fit; holdout: used only to validate
    unit: str = ""
    source: str = ""
    accessed: str = ""
    quality: str = ""              # A, B or C (see the user guide)
    verified: bool = False
    notes: str = ""


@dataclass
class Measurement:
    """How exchange data from one place are distorted relative to the model's genuine holdings."""
    code: str
    wash_share: float = 0.0        # share of reported exchange volume that is wash trading at exchanges based here
    turnover: float = 1.0          # genuine turnover of holdings at exchanges based here, relative to elsewhere
    source: str = ""
    verified: bool = False


@dataclass
class ParamSpec:
    name: str
    free: bool = False
    value: float | None = None     # start value if free, fixed value if not (blank: the interface value)
    lower: float | None = None
    upper: float | None = None
    judgement_low: float | None = None    # for fixed parameters: range used for the judgement band in validation
    judgement_high: float | None = None
    notes: str = ""


@dataclass
class Hypothesis:
    id: str
    statement: str
    test: str = ""                 # which observations or results would support or refute it
    source: str = ""


@dataclass
class Design:
    episodes: list = field(default_factory=list)          # list[Episode]; baseline is implicit
    observations: list = field(default_factory=list)      # list[Observation]
    measurement: list = field(default_factory=list)       # list[Measurement]
    params: list = field(default_factory=list)            # list[ParamSpec]
    hypotheses: list = field(default_factory=list)        # list[Hypothesis]
    concept: str = "a"
    starts: int = 3
    seed: int = 1
    label: str = ""
    synthetic: bool = False                               # values generated by the tool, not observed

    # ---- access --------------------------------------------------------------------
    def episode(self, name):
        if name == BASELINE:
            return Episode(BASELINE, "The coded world as loaded")
        for e in self.episodes:
            if e.name == name:
                return e
        raise KeyError(name)

    def episode_names(self):
        return [BASELINE] + [e.name for e in self.episodes]

    def targets(self):
        return [o for o in self.observations if o.role == "target"]

    def holdouts(self):
        return [o for o in self.observations if o.role == "holdout"]

    def free_params(self):
        return [p for p in self.params if p.free]

    def param(self, name):
        for p in self.params:
            if p.name == name:
                return p
        return None

    def measurement_for(self, code):
        for m in self.measurement:
            if m.code == code:
                return m
        return Measurement(code)

    def with_values(self, values: dict):
        """Copy with observation values replaced (id -> value)."""
        d = copy.deepcopy(self)
        for o in d.observations:
            if o.id in values:
                o.value = values[o.id]
        return d

    # ---- serialisation ---------------------------------------------------------------
    def to_dict(self):
        return asdict(self)

    @staticmethod
    def from_dict(d):
        eps = [Episode(e["name"], e.get("description", ""), [Change(**c) for c in e.get("changes", [])]) for e in d.get("episodes", [])]
        return Design(episodes=eps, observations=[Observation(**o) for o in d.get("observations", [])],
                      measurement=[Measurement(**m) for m in d.get("measurement", [])],
                      params=[ParamSpec(**p) for p in d.get("params", [])],
                      hypotheses=[Hypothesis(**h) for h in d.get("hypotheses", [])],
                      **{k: d[k] for k in ("concept", "starts", "seed", "label", "synthetic") if k in d})


# ---- episodes --------------------------------------------------------------------------
_J_TYPES = {f.name: f.type for f in fields(Jurisdiction)}


def coerce(field_name, value, for_settings=False):
    """Convert a template cell to the type of the world field it changes. Raises ValueError with a message."""
    if for_settings:
        if field_name == "scenario_year":
            return int(float(value))
        x = float(value)
        if not 0 <= x <= 1:
            raise ValueError("must be between 0 and 1")
        return x
    t = str(_J_TYPES[field_name])
    if field_name == "domestic_exchanges_permitted":
        v = str(value).strip().lower()
        if v not in ("yes", "no", "true", "false"):
            raise ValueError("must be yes or no")
        return v in ("yes", "true")
    if field_name == "info_exchange_from":
        return None if value in ("", None) or str(value).strip().lower() in ("none", "never") else int(float(value))
    if field_name == "effective_rate":
        if value in ("", None):
            return None
    if "float" in t:
        x = float(value)
        if field_name in ("visibility_domestic_custodial", "visibility_self_hosted", "residence_topup",
                          "effective_rate", "offshore_incorporation_share") and not 0 <= x <= 1:
            raise ValueError("must be between 0 and 1")
        if x < 0:
            raise ValueError("must not be negative")
        return x
    return "" if value is None else str(value).strip()


def apply_episode(world: World, ep: Episode) -> World:
    """Copy of the coded world with an episode's changes applied."""
    w = World.from_dict(world.to_dict())
    for ch in ep.changes:
        if ch.target == "settings":
            setattr(w.settings, ch.field, ch.value)
        else:
            setattr(w.jurisdictions[w.index(ch.target)], ch.field, ch.value)
    return w


# ---- fingerprints (pre-registration) ------------------------------------------------------
def canonical(obj) -> str:
    return json.dumps(obj, sort_keys=True, separators=(",", ":"), ensure_ascii=False, default=str)


def fingerprint(obj) -> str:
    return hashlib.sha256(canonical(obj).encode("utf-8")).hexdigest()


def world_fingerprint(world: World) -> str:
    """Fingerprint of the coded law and settings (provenance fields included)."""
    return fingerprint(world.to_dict())
