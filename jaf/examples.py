"""Illustrative empirical design on the invented world (build plan s 14).

It mirrors the two designs the later empirical work will use, on hypothetical states only:
  * a single reform (in the manner of India's 2022 regime): Country A raises its effective tax on returns from
    holdings and makes its domestic exchanges withhold;
  * staggered adoption of automatic exchange of information (in the manner of the CARF waves): the scenario
    year steps from before any exchange to successive waves.
Its "observed" values are synthetic: the model's own outputs at known parameter values (TRUTH, with every other
setting at its default) plus noise of the stated size. They are not observations of anything and exist so the
workflow can be seen and tested. If the interface settings are changed from their defaults, the synthetic data no
longer match the model exactly.
"""
from __future__ import annotations
import numpy as np
from .world import World, illustrative_world
from .design import Design, Episode, Change, Observation, Measurement, ParamSpec, Hypothesis

SYN = "Synthetic: generated by the tool at known parameter values; not an observation"
SRC = "Illustrative only: hypothetical change, not real law"

# parameter values used to generate the synthetic data (the "truth" the recovery test should find)
TRUTH = {"theta0": 3.4, "mobility_custodial": 0.55}


def illustrative_design_skeleton() -> Design:
    eps = [
        Episode("reform", "Country A raises its effective rate on returns to 36% and requires domestic exchanges to withhold (a single reform, in the manner of India 2022; invented).",
                [Change("A", "effective_rate", 0.36, SRC, True), Change("A", "collection", "domestic_withholding", SRC, True)]),
        Episode("before_exchange", "Year 2026: no state yet exchanges information (before the first wave).",
                [Change("settings", "scenario_year", 2026, SRC, True)]),
        Episode("wave_2029", "Year 2029: Country B joins automatic exchange (second wave).",
                [Change("settings", "scenario_year", 2029, SRC, True)]),
        Episode("wave_2030", "Year 2030: Hub Two joins automatic exchange (third wave).",
                [Change("settings", "scenario_year", 2030, SRC, True), Change("H2", "info_exchange_from", 2030, SRC, True)]),
    ]
    O = lambda *a, **k: Observation(*a, **k, source=SYN, quality="synthetic", verified=False)
    obs = [
        O("T1", "resident_domestic_exchange_share", "A", "baseline", sd=0.02, unit="share"),
        O("T2", "resident_domestic_exchange_share", "A", "reform", "baseline", "ratio", sd=0.03, unit="ratio, reform / baseline"),
        O("T3", "resident_custodial_share", "A", "reform", "baseline", "ratio", sd=0.02, unit="ratio, reform / baseline"),
        O("T4", "custodial_share_by_base", "H1", "baseline", sd=0.02, unit="share"),
        O("T5", "exit_share", "", "reform", "baseline", "ratio", sd=0.03, unit="ratio, reform / baseline"),
        O("T6", "resident_offshore_unexchanged_share", "B", "wave_2029", "baseline", "difference", sd=0.01, unit="difference"),
        O("T7", "resident_visible_share", "A", "baseline", "before_exchange", "ratio", sd=0.02, unit="ratio, baseline / before"),
        O("V1", "resident_custodial_share", "B", "wave_2029", "baseline", "ratio", role="holdout", sd=0.02, unit="ratio"),
        O("V2", "resident_offshore_unexchanged_share", "A", "wave_2030", "wave_2029", "difference", role="holdout", sd=0.01, unit="difference"),
        O("V3", "custodial_share_by_base", "A", "reform", "baseline", "ratio", role="holdout", sd=0.03, unit="ratio, reform / baseline"),
    ]
    meas = [Measurement("H1", 0.30, 1.0, "Illustrative: hypothetical wash-trading share", True),
            Measurement("H2", 0.20, 1.0, "Illustrative: hypothetical wash-trading share", True)]
    params = [
        ParamSpec("theta0", True, 3.0, 2.0, 6.0, notes="Free: identified mainly by the reform responses"),
        ParamSpec("mobility_custodial", True, 0.40, 0.05, 1.5, notes="Free: identified by offshore exchange shares"),
        ParamSpec("beta", False, 25.0, judgement_low=15.0, judgement_high=35.0,
                  notes="Fixed by judgement: with these targets it trades off almost one for one with theta0 (not separately identified)"),
        ParamSpec("exit_weight", False, 0.60, judgement_low=0.3, judgement_high=1.2, notes="Fixed by judgement: the exit share's response barely depends on it (not identified)"),
        ParamSpec("sigma", False, 1.0, judgement_low=0.5, judgement_high=1.5, notes="Fixed by judgement"),
    ]
    hyp = [
        Hypothesis("EH1", "After a rise in the effective tax on exchange-held holdings with domestic withholding, residents' trading moves from domestic to foreign exchanges.",
                   "T2 below 1 with an interval excluding 1; holdout V3 predicted within its band.", SRC),
        Hypothesis("EH2", "Each wave of automatic exchange reduces the share of residents' exchange activity outside the reporting net, net of relocation to non-participating hubs.",
                   "T6 and holdout V2 negative; V2 predicted within its band.", SRC),
    ]
    return Design(eps, obs, meas, params, hyp, concept="a", starts=2, seed=7,
                  label="Illustrative design (invented states, synthetic data)", synthetic=True)


def synthetic_values(world: World, design: Design, truth: dict, noise=True, seed=2028, base=None):
    """Model outputs at `truth` for every observation, plus normal noise with each observation's sd."""
    from .estimate import Model
    m = Model(world, design, base)
    obs = design.observations
    v = m.moments(m.full(override=truth), obs)
    if noise:
        v = v + np.random.default_rng(seed).normal(0.0, [o.sd for o in obs])
    return {o.id: float(x) for o, x in zip(obs, v)}


_CACHE = {}


def illustrative_design(world: World | None = None) -> Design:
    """The illustrative design with synthetic values, generated on `world` at the default interface settings
    and the parameter values in TRUTH. Cached by world fingerprint (review finding 10)."""
    from .design import world_fingerprint
    import copy
    world = world or illustrative_world()
    key = world_fingerprint(world)
    if key not in _CACHE:
        d = illustrative_design_skeleton()
        _CACHE[key] = d.with_values({k: round(v, 4) for k, v in synthetic_values(world, d, TRUTH).items()})
    return copy.deepcopy(_CACHE[key])


def is_illustrative_world(world: World) -> bool:
    from .design import world_fingerprint
    return world_fingerprint(world) == world_fingerprint(illustrative_world())
